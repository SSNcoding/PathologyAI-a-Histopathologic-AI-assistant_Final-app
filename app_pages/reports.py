"""Patient Report — a full pathology-style PDF with demographics, clinical summary,
quantitative findings, heatmap, and recommended next steps."""

from datetime import datetime

import streamlit as st

from config.settings import REPORTS_DIR, UPLOADS_DIR
from core.permissions import can
from core.session_state import current_user, has_image
from models.disease_registry import get_organ
from services.dicom_export import build_dicom_secondary_capture, is_dicom_available
from services.pdf_report import build_pdf_report
from ui.components import disclaimer_banner, no_image_warning
from ui.theme import render_page_hero


def render() -> None:
    render_page_hero("Patient Report", "Generate a downloadable pathology PDF report")
    user = current_user()
    if not user or not can(user.get("role"), "generate_patient_report"):
        st.error(
            "Patient Report generation is limited to pathologist and administrator roles "
            "on this platform — see your Profile page for your current role."
        )
        return
    if not st.session_state.ai_results:
        st.warning("Run **AI Analysis** first to populate report data.")
        if not has_image():
            no_image_warning("generate reports")
        return

    settings = st.session_state.settings
    ai = st.session_state.ai_results
    organ_name = get_organ(ai.get("organ", "breast")).display_name

    st.subheader("Patient & Specimen Details")
    c1, c2, c3 = st.columns(3)
    with c1:
        patient_id = st.text_input("Patient / Specimen ID", value="SPEC-2026-001")
        patient_name = st.text_input("Patient Name (optional)", value="")
    with c2:
        patient_age = st.text_input("Age", value="")
        patient_sex = st.selectbox("Sex", ["", "Female", "Male", "Other/Unspecified"])
    with c3:
        physician = st.text_input("Reviewing Physician", value=settings["report_physician"])
        institution = st.text_input("Institution", value=settings["report_institution"])

    disclaimer_banner(
        "This report is generated by a research/educational platform and is not a substitute "
        "for pathologist review. Staging, survival, and biomarker predictions are intentionally "
        "excluded — they require clinical data beyond a single image."
    )

    if st.button("Generate PDF Report", type="primary", use_container_width=True):
        thumb_path = UPLOADS_DIR / f"thumb_{datetime.now():%Y%m%d_%H%M%S}.png"
        st.session_state.current_image.save(thumb_path)
        heatmap_path = UPLOADS_DIR / f"heatmap_{datetime.now():%Y%m%d_%H%M%S}.png"
        if st.session_state.heatmap_image:
            st.session_state.heatmap_image.save(heatmap_path)
        else:
            heatmap_path = None

        pdf_bytes = build_pdf_report(
            patient_id=patient_id,
            slide_name=st.session_state.current_image_name or "unknown",
            physician=physician,
            institution=institution,
            summary=ai["summary"],
            findings=ai["findings"],
            tissue_stats=ai["tissue"],
            cell_stats=ai["cells"],
            thumbnail_path=thumb_path,
            patient_name=patient_name,
            patient_age=patient_age,
            patient_sex=patient_sex,
            organ=organ_name,
            architecture=ai.get("architecture", ""),
            model_mode=ai.get("model_mode", ""),
            risk_level=ai.get("risk_level", "low"),
            tumor_metrics=ai.get("tumor_metrics"),
            quality=ai.get("quality"),
            heatmap_path=heatmap_path,
            processing_time_s=ai.get("processing_time_s"),
            model_version=ai.get("model_version"),
        )
        out_path = REPORTS_DIR / f"report_{patient_id}_{datetime.now():%Y%m%d_%H%M%S}.pdf"
        out_path.write_bytes(pdf_bytes)
        st.session_state["_last_report_bytes"] = pdf_bytes
        st.session_state["_last_report_name"] = out_path.name
        st.success(f"Report ready: `{out_path.name}`")

    if st.session_state.get("_last_report_bytes"):
        st.download_button(
            "Download PDF Report",
            data=st.session_state["_last_report_bytes"],
            file_name=st.session_state["_last_report_name"],
            mime="application/pdf",
            type="primary",
            use_container_width=True,
        )

    st.markdown("---")
    st.subheader("DICOM Export (optional)")
    if not is_dicom_available():
        st.caption(
            "Not enabled — run `pip install pydicom` (see requirements.txt) to export this "
            "analysis as a DICOM Secondary Capture file for PACS/DICOM-viewer compatibility. "
            "Note: this produces a standalone file, not a live PACS upload — see "
            "services/dicom_export.py for what a real PACS integration (C-STORE) would need."
        )
    elif st.session_state.heatmap_image:
        if st.button("Build DICOM (.dcm) from heatmap", use_container_width=True):
            dicom_bytes = build_dicom_secondary_capture(
                image=st.session_state.heatmap_image,
                patient_id=patient_id,
                patient_name=patient_name,
                report_summary=ai["summary"],
                organ=organ_name,
                model_mode=ai.get("model_mode", ""),
                model_version=ai.get("model_version"),
                institution=institution,
            )
            st.session_state["_last_dicom_bytes"] = dicom_bytes
            st.session_state["_last_dicom_name"] = f"pathologyai_{patient_id}_{datetime.now():%Y%m%d_%H%M%S}.dcm"
        if st.session_state.get("_last_dicom_bytes"):
            st.download_button(
                "Download DICOM (.dcm)",
                data=st.session_state["_last_dicom_bytes"],
                file_name=st.session_state["_last_dicom_name"],
                mime="application/dicom",
                use_container_width=True,
            )
    else:
        st.caption("Run AI Analysis first so there's a heatmap to package as the DICOM pixel data.")
